export function videoTranscodeArgs(
  filePath: string,
  outputPath: string,
  downscale: boolean,
): string[] {
  return [
    "-hide_banner",
    "-loglevel",
    "error",
    "-nostdin",
    "-i",
    filePath,
    "-vf",
    downscale ? "scale=w='min(1024,iw)':h=-2" : "null",
    "-map",
    "0:v:0",
    "-map",
    "0:a:0?",
    "-c:v",
    "libvpx-vp9",
    "-deadline",
    "realtime",
    "-cpu-used",
    "8",
    "-crf",
    "32",
    "-b:v",
    "0",
    "-strict",
    "-2",
    "-c:a",
    "opus",
    "-b:a",
    "128k",
    "-f",
    "webm",
    outputPath,
  ];
}
